//===----------------------------------------------------------------------===//
// TileSelectionPass — resolve, validate, and annotate the final tile shape
//===----------------------------------------------------------------------===//
//
// Pipeline position:
//   LayoutPropagationAnnotation → LayoutPropagationNormalization
//     → TileAnalyzerPass → **TileSelectionPass** → TensorToCudaTileConversion
//
// Purpose:
//   Consumes tile hints from three sources (in priority order) and produces a
//   single, validated "tile_size" DenseI32ArrayAttr on the GraphOp:
//
//     1. tile_size pass option              — forwarded from compilation
//        options (highest priority; allows an explicit caller choice to
//        override a tile embedded in the graph).
//     2. "tile_size" attribute on GraphOp   — set by the graph producer via
//        tensor-ir.
//     3. "tile_candidates" attribute        — generated by TileAnalyzerPass;
//        the pass picks tile_candidates[0] (best-scored candidate).
//        TileAnalyzerPass guarantees this attribute is present whenever
//        an iteration space exists — it falls back to a conservative tile
//        when its scoring tracks produce nothing — so this source covers
//        both the analyzer-driven and fallback paths.
//
//   If none of the above are available the pass emits an error.
//
// Validation:
//   When the "iteration_space" attribute is present on the graph terminator
//   (set by LayoutPropagationNormalizationPass), the selected tile is checked
//   for rank match and per-dimension validity (power-of-2, within bounds).
//   Invalid tiles cause the pass to emit a diagnostic and fail.
//
// Guarantees to downstream passes:
//   • "tile_size" is always present on GraphOp after this pass succeeds.
//   • "tile_candidates" is removed (cleanup — consumed by this pass).
//   • The tile shape has been validated against the iteration space when that
//     information is available.
//   • TensorToCudaTileConversionPass reads "tile_size" from the GraphOp
//     attribute and does not need its own tile-size pass option for the
//     LayoutPropagation codegen strategy.
//
// Failure modes:
//   • No tile source available → error with list of expected sources.
//   • tile_candidates is empty or malformed → error.
//   • Tile rank does not match iteration space rank → error with both shapes.
//   • Tile dimension is not power-of-2 or exceeds shape → error.
//
//===----------------------------------------------------------------------===//

