/// Extract the iteration space shape from the "iteration_space" attribute on
/// the graph's terminator via LayoutSourceAttrInterface::getShape().
/// Returns failure if the attribute is absent or does not implement the
/// interface.
static FailureOr<LayoutSourceAttrInterface>
extractIterationSpace(GraphOp graphOp) {
  Operation *terminator = graphOp.getBody()->getTerminator();
  if (!terminator) {
    return failure();
  }

  auto layoutSource = terminator->getAttrOfType<LayoutSourceAttrInterface>(
      TensorIRDialect::getIterationSpaceAttrName());
  if (!layoutSource) {
    return failure();
  }

  return layoutSource;
}

/// Check if the iteration_space shape has any dynamic dimensions.
static bool hasDynamicDims(ArrayRef<DimSize> shape) {
  return llvm::any_of(shape, [](DimSize d) { return d <= 0; });
}

struct TileSelectionPass
    : public impl::TileSelectionPassBase<TileSelectionPass> {

  using TileSelectionPassBase::TileSelectionPassBase;

  void runOnOperation() override {
    GraphOp graphOp = getOperation();
    MLIRContext *ctx = graphOp.getContext();

    // ── Step 1: Resolve tile shape (priority order) ─────────────────
    SmallVector<int32_t> selectedTile;

    // Source 1: tile_size pass option (from compilation options)
    if (!tile_size.empty()) {
      selectedTile.assign(tile_size.begin(), tile_size.end());
      LLVM_DEBUG(llvm::dbgs()
                 << "TileSelectionPass: using tile_size from pass option: "
                 << vectorToString(selectedTile) << "\n");
    }
    // Source 2: "tile_size" attribute on GraphOp (from tensor-ir)
    else if (auto tileSizeAttr = graphOp->getAttrOfType<DenseI32ArrayAttr>(
                 TensorIRDialect::getTileSizeAttrName())) {
      auto values = tileSizeAttr.asArrayRef();
      selectedTile.assign(values.begin(), values.end());
      LLVM_DEBUG(llvm::dbgs()
                 << "TileSelectionPass: using tile_size attr from GraphOp: "
                 << vectorToString(selectedTile) << "\n");
    }
    // Source 3: "tile_candidates" attribute on GraphOp (from TileAnalyzerPass)
    else if (auto candidatesAttr = graphOp->getAttrOfType<ArrayAttr>(
                 TensorIRDialect::getTileCandidatesAttrName())) {
      if (candidatesAttr.empty()) {
        graphOp.emitError("tile_candidates is empty and no tile shape provided "
                          "through tensor-ir or compilation options");
        return signalPassFailure();
      }
      auto best = dyn_cast<DenseI32ArrayAttr>(candidatesAttr[0]);
      if (!best) {
        graphOp.emitError("tile_candidates[0] is not a DenseI32ArrayAttr");
        return signalPassFailure();
      }
      auto values = best.asArrayRef();
      selectedTile.assign(values.begin(), values.end());
      LLVM_DEBUG(llvm::dbgs() << "TileSelectionPass: using tile_candidates[0]: "
                              << vectorToString(selectedTile) << "\n");
    }
    // No source available: fail. TileSelectionPass must expect at least one
    // tile candidate.
    else {
      graphOp.emitError("No tile shape source available. Expected one of: "
                        "tile_size pass option, \"tile_size\" attr on GraphOp, "
                        "or \"tile_candidates\" from TileAnalyzerPass");
      return signalPassFailure();
    }

    // ── Step 2: Verify tile against iteration space ─────────────────
    auto rootLayout = extractIterationSpace(graphOp);
    if (succeeded(rootLayout)) {
      auto iterSpaceShape = rootLayout->getShape();
      if (static_cast<int64_t>(selectedTile.size()) !=
          static_cast<int64_t>(iterSpaceShape.size())) {
        graphOp.emitError()
            << "Selected tile " << vectorToString(selectedTile)
            << " is not valid for iteration space "
            << vectorToString(iterSpaceShape) << " — rank mismatch (tile rank "
            << selectedTile.size() << " vs iteration space rank "
            << iterSpaceShape.size() << ")";
        return signalPassFailure();
      }

      // Skip per-dim validation when the iteration space has dynamic dims
      // (tile validity can only be checked at runtime).
      if (!hasDynamicDims(iterSpaceShape)) {
        GpuArchitecture gpu(/*warp_size=*/32, /*cache_line=*/128);
        TileCandidateGenerator generator(gpu, /*maxCandidates=*/1);
        if (!generator.isValidTile(selectedTile, iterSpaceShape)) {
          graphOp.emitError()
              << "Selected tile " << vectorToString(selectedTile)
              << " is not valid for iteration space "
              << vectorToString(iterSpaceShape);
          return signalPassFailure();
        }
      }
    }

    // ── Step 3: Update IR annotations ──────────────────────────────
    graphOp->removeAttr(TensorIRDialect::getTileCandidatesAttrName());
    graphOp->setAttr(TensorIRDialect::getTileSizeAttrName(),
                     DenseI32ArrayAttr::get(ctx, selectedTile));

    LLVM_DEBUG(llvm::dbgs() << "TileSelectionPass: set tile_size = "
                            << vectorToString(selectedTile) << " on "
                            << graphOp.getSymName() << "\n");
  }
};

